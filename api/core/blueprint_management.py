"""
Blueprint management: Manual synthesis from Dafny specification.
Pure functions matching Dafny BlueprintManagement module.

See: api/verification/blueprint_management.dfy :: BlueprintManagement
"""

import icontract
from api.core.models import SystemState, Blueprint, Result, Owner


def _blueprint_name_unique(state: SystemState, name: str, owner: Owner) -> bool:
    """
    Helper predicate matching Dafny BlueprintNameUnique.
    Checks if blueprint name is unique for the owner (case-insensitive).
    """
    name_lower = name.lower()
    for blueprint_id, blueprint in state.blueprints.items():
        if blueprint.owner == owner and blueprint.name.lower() == name_lower:
            return False
    return True


def _check_blueprint_ownership(state: SystemState, blueprint_id: str, owner_id: str) -> bool:
    """
    Check if blueprint is owned by owner_id (matching Dafny spec).
    
    Dafny spec: p.owner == Authenticated(ownerId) || p.owner == Anonymous(ownerId)
    """
    if blueprint_id not in state.blueprints:
        return False
    
    blueprint = state.blueprints[blueprint_id]
    # Check if owner matches Authenticated(ownerId) OR Anonymous(ownerId)
    return (
        blueprint.owner == Owner.authenticated(owner_id) or
        blueprint.owner == Owner.anonymous(owner_id)
    )


@icontract.require(
    lambda state, new_blueprint_id, name, description, owner:
        state is not None and
        state.validate() and
        new_blueprint_id not in state.blueprints and
        len(name) > 0 and
        len(name) <= 255 and
        len(description) <= 1000 and
        len(name) <= 255 and
        len(description) <= 1000,
    "Preconditions: Valid state, unique blueprint ID, name length 1-255, description <= 1000"
)
@icontract.snapshot(lambda state, new_blueprint_id, name, description, owner: state.blueprints.keys(), name="old_blueprint_ids")
@icontract.ensure(
    lambda result, state, new_blueprint_id, name, description, owner, OLD:
        result[0].validate() and
        (result[1].success == True) == (new_blueprint_id in result[0].blueprints),
    "Postconditions: Valid state, blueprint created iff success"
)
def create_blueprint_core(
    state: SystemState,
    new_blueprint_id: str,
    name: str,
    description: str,
    owner: Owner
) -> tuple[SystemState, Result]:
    """
    Create blueprint: Pure function matching Dafny CreateBlueprint.
    
    Args:
        state: Current system state snapshot
        new_blueprint_id: UUID generated by Shell
        name: Blueprint name (must be unique for owner, case-insensitive)
        description: Blueprint description
        owner: Owner (Authenticated or Anonymous)
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/blueprint_management.dfy :: CreateBlueprint
    """
    # Check name uniqueness
    if not _blueprint_name_unique(state, name, owner):
        return (state, Result.failure("Conflict", "Name taken"))
    
    # Create new blueprint with empty file_ids set
    new_blueprint = Blueprint(
        blueprint_id=new_blueprint_id,
        name=name,
        description=description,
        owner=owner,
        file_ids=set()
    )
    
    # Update blueprints map
    new_blueprints = {**state.blueprints, new_blueprint_id: new_blueprint}
    new_state = SystemState(blueprints=new_blueprints, files=state.files)
    new_state.validate()
    
    return (new_state, Result.ok(new_blueprint_id))


@icontract.require(
    lambda state, blueprint_id, owner_id:
        state is not None and
        state.validate() and
        blueprint_id in state.blueprints and
        _check_blueprint_ownership(state, blueprint_id, owner_id),
    "Preconditions: Valid state, blueprint exists, owner matches"
)
@icontract.snapshot(lambda state, blueprint_id, owner_id: state.files.keys(), name="old_file_ids")
@icontract.ensure(
    lambda result, state, blueprint_id, owner_id, OLD:
        result[0].validate() and
        (result[1].success == True) == (
            blueprint_id not in result[0].blueprints and
            all(fid not in result[0].files for fid in OLD.old_file_ids 
                if state.files.get(fid) and state.files[fid].blueprint_id == blueprint_id)
        ),
    "Postconditions: Valid state, blueprint and all its files deleted iff success"
)
def delete_blueprint_core(
    state: SystemState,
    blueprint_id: str,
    owner_id: str
) -> tuple[SystemState, Result]:
    """
    Delete blueprint: Pure function matching Dafny DeleteBlueprint.
    
    Cascade deletion: Removes blueprint and all files belonging to it.
    
    Args:
        state: Current system state snapshot
        blueprint_id: Blueprint to delete
        owner_id: Owner identifier
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/blueprint_management.dfy :: DeleteBlueprint
    """
    if blueprint_id not in state.blueprints:
        return (state, Result.failure("NotFound", "Blueprint not found"))
    
    # Check ownership
    if not _check_blueprint_ownership(state, blueprint_id, owner_id):
        return (state, Result.failure("Unauthorized", "Blueprint ownership mismatch"))
    
    # Cascade: Identify files to remove
    files_to_delete = {
        file_id for file_id, file_obj in state.files.items()
        if file_obj.blueprint_id == blueprint_id
    }
    
    # Remove files
    new_files = {
        file_id: file_obj for file_id, file_obj in state.files.items()
        if file_id not in files_to_delete
    }
    
    # Remove blueprint
    new_blueprints = {
        pid: proj for pid, proj in state.blueprints.items()
        if pid != blueprint_id
    }
    
    new_state = SystemState(blueprints=new_blueprints, files=new_files)
    new_state.validate()
    
    return (new_state, Result.ok(True))
