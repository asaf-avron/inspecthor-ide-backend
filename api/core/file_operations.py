"""
File operations: Manual synthesis from Dafny specification.
Pure functions matching Dafny FileOperations module.

See: api/verification/file_operations.dfy :: FileOperations
"""

import icontract
from api.core.models import SystemState, File, FileType, Result, Owner, Blueprint


def _filename_unique(state: SystemState, blueprint_id: str, filename: str) -> bool:
    """
    Helper predicate matching Dafny FilenameUnique.
    Checks if filename is unique within the blueprint.
    """
    for file_id, file_obj in state.files.items():
        if file_obj.blueprint_id == blueprint_id and file_obj.filename == filename:
            return False
    return True


def _check_ownership(state: SystemState, blueprint_id: str, owner_id: str) -> bool:
    """
    Check if blueprint is owned by owner_id (matching Dafny spec).
    
    Dafny spec: s.blueprints[blueprintId].owner == Authenticated(ownerId) || 
                s.blueprints[blueprintId].owner == Anonymous(ownerId)
    
    This means owner_id can match either:
    - Authenticated(userId) if blueprint.owner.user_id == owner_id
    - Anonymous(apiKeyHash) if blueprint.owner.api_key_hash == owner_id
    """
    if blueprint_id not in state.blueprints:
        return False
    
    blueprint = state.blueprints[blueprint_id]
    # Check if owner matches Authenticated(ownerId) OR Anonymous(ownerId)
    return (
        blueprint.owner == Owner.authenticated(owner_id) or
        blueprint.owner == Owner.anonymous(owner_id)
    )


@icontract.require(
    lambda state, new_file_id, blueprint_id, filename, content, file_type, owner_id:
        state is not None and
        state.validate() and
        len(filename) > 0 and
        new_file_id not in state.files and
        blueprint_id in state.blueprints and
        _check_ownership(state, blueprint_id, owner_id) and
        _filename_unique(state, blueprint_id, filename) and
        len(content.encode('utf-8')) < 1000000,
    "Preconditions: Valid state, non-empty filename, unique ID, blueprint exists and owned, filename unique, content size < 1MB"
)
@icontract.ensure(
    lambda result, state, new_file_id, blueprint_id, filename, content, file_type, owner_id:
        result[0].validate() and
        (result[1].success == True) == (new_file_id in result[0].files and new_file_id in result[0].blueprints[blueprint_id].file_ids),
    "Postconditions: Valid state, file created iff success"
)
def save_file_core(
    state: SystemState,
    new_file_id: str,
    blueprint_id: str,
    filename: str,
    content: str,
    file_type: FileType,
    owner_id: str
) -> tuple[SystemState, Result]:
    """
    Save file: Pure function matching Dafny SaveFile.
    
    Args:
        state: Current system state snapshot
        new_file_id: UUID generated by Shell
        blueprint_id: Blueprint to add file to
        filename: Filename (must be unique in blueprint)
        content: File content
        file_type: File type enum
        owner_id: Owner identifier (user_id or api_key_hash)
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/file_operations.dfy :: SaveFile
    """
    # Check blueprint exists
    if blueprint_id not in state.blueprints:
        return (state, Result.failure("NotFound", "Blueprint not found"))
    
    # Check ownership
    if not _check_ownership(state, blueprint_id, owner_id):
        return (state, Result.failure("Unauthorized", "Blueprint ownership mismatch"))
    
    # Check filename uniqueness
    if not _filename_unique(state, blueprint_id, filename):
        return (state, Result.failure("Conflict", "Filename exists"))
    
    # Create new file
    size_bytes = len(content.encode('utf-8'))
    new_file = File(
        file_id=new_file_id,
        blueprint_id=blueprint_id,
        filename=filename,
        content=content,
        file_type=file_type,
        size_bytes=size_bytes,
        renamed=False
    )
    
    # Update files map
    new_files = {**state.files, new_file_id: new_file}
    
    # Update blueprint's file_ids set
    old_blueprint = state.blueprints[blueprint_id]
    new_file_ids = old_blueprint.file_ids | {new_file_id}
    new_blueprint = Blueprint(
        blueprint_id=old_blueprint.blueprint_id,
        name=old_blueprint.name,
        description=old_blueprint.description,
        owner=old_blueprint.owner,
        file_ids=new_file_ids
    )
    new_blueprints = {**state.blueprints, blueprint_id: new_blueprint}
    
    new_state = SystemState(blueprints=new_blueprints, files=new_files)
    new_state.validate()
    
    return (new_state, Result.ok(new_file_id))


@icontract.require(
    lambda state, file_id, new_content, new_filename, owner_id:
        state is not None and
        state.validate() and
        file_id in state.files,
    "Preconditions: Valid state, file exists"
)
@icontract.ensure(
    lambda result, state, file_id, new_content, new_filename, owner_id:
        result[0].validate(),
    "Postconditions: Valid state"
)
def update_file_core(
    state: SystemState,
    file_id: str,
    new_content: str,
    new_filename: str,  # Empty string if no rename
    owner_id: str
) -> tuple[SystemState, Result]:
    """
    Update file: Pure function matching Dafny UpdateFile.
    
    Args:
        state: Current system state snapshot
        file_id: File to update
        new_content: New file content
        new_filename: New filename (empty string to keep current)
        owner_id: Owner identifier
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/file_operations.dfy :: UpdateFile
    """
    if file_id not in state.files:
        return (state, Result.failure("NotFound", "File not found"))
    
    old_file = state.files[file_id]
    blueprint_id = old_file.blueprint_id
    
    # Check ownership
    if not _check_ownership(state, blueprint_id, owner_id):
        return (state, Result.failure("Unauthorized", "Blueprint ownership mismatch"))
    
    # Check filename uniqueness if renaming
    if new_filename and new_filename != old_file.filename:
        if not _filename_unique(state, blueprint_id, new_filename):
            return (state, Result.failure("Conflict", "Filename exists"))
    
    # Determine actual filename and renamed flag
    actual_filename = new_filename if new_filename else old_file.filename
    is_renamed = old_file.renamed or (new_filename != "" and new_filename != old_file.filename)
    
    # Create updated file
    size_bytes = len(new_content.encode('utf-8'))
    new_file = File(
        file_id=file_id,
        blueprint_id=blueprint_id,
        filename=actual_filename,
        content=new_content,
        file_type=old_file.file_type,
        size_bytes=size_bytes,
        renamed=is_renamed
    )
    
    # Update files map
    new_files = {**state.files, file_id: new_file}
    new_state = SystemState(blueprints=state.blueprints, files=new_files)
    new_state.validate()
    
    return (new_state, Result.ok(file_id))


@icontract.require(
    lambda state, file_id, owner_id:
        state is not None and
        state.validate() and
        file_id in state.files,
    "Preconditions: Valid state, file exists"
)
@icontract.ensure(
    lambda result, state, file_id, owner_id:
        result[0].validate() and
        (result[1].success == True) == (file_id not in result[0].files),
    "Postconditions: Valid state, file deleted iff success"
)
def delete_file_core(
    state: SystemState,
    file_id: str,
    owner_id: str
) -> tuple[SystemState, Result]:
    """
    Delete file: Pure function matching Dafny DeleteFile.
    
    Args:
        state: Current system state snapshot
        file_id: File to delete
        owner_id: Owner identifier
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/file_operations.dfy :: DeleteFile
    """
    if file_id not in state.files:
        return (state, Result.failure("NotFound", "File not found"))
    
    file_obj = state.files[file_id]
    blueprint_id = file_obj.blueprint_id
    
    # Check ownership
    if not _check_ownership(state, blueprint_id, owner_id):
        return (state, Result.failure("Unauthorized", "Blueprint ownership mismatch"))
    
    # Remove from files map
    new_files = {fid: f for fid, f in state.files.items() if fid != file_id}
    
    # Remove from blueprint's file_ids set
    old_blueprint = state.blueprints[blueprint_id]
    new_file_ids = old_blueprint.file_ids - {file_id}
    new_blueprint = Blueprint(
        blueprint_id=old_blueprint.blueprint_id,
        name=old_blueprint.name,
        description=old_blueprint.description,
        owner=old_blueprint.owner,
        file_ids=new_file_ids
    )
    new_blueprints = {**state.blueprints, blueprint_id: new_blueprint}
    
    new_state = SystemState(blueprints=new_blueprints, files=new_files)
    new_state.validate()
    
    return (new_state, Result.ok(True))
