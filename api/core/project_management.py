"""
Project management: Manual synthesis from Dafny specification.
Pure functions matching Dafny ProjectManagement module.

See: api/verification/project_management.dfy :: ProjectManagement
"""

import icontract
from api.core.models import SystemState, Project, Result, Owner


def _project_name_unique(state: SystemState, name: str, owner: Owner) -> bool:
    """
    Helper predicate matching Dafny ProjectNameUnique.
    Checks if project name is unique for the owner (case-insensitive).
    """
    name_lower = name.lower()
    for project_id, project in state.projects.items():
        if project.owner == owner and project.name.lower() == name_lower:
            return False
    return True


def _check_project_ownership(state: SystemState, project_id: str, owner_id: str) -> bool:
    """
    Check if project is owned by owner_id (matching Dafny spec).
    
    Dafny spec: p.owner == Authenticated(ownerId) || p.owner == Anonymous(ownerId)
    """
    if project_id not in state.projects:
        return False
    
    project = state.projects[project_id]
    # Check if owner matches Authenticated(ownerId) OR Anonymous(ownerId)
    return (
        project.owner == Owner.authenticated(owner_id) or
        project.owner == Owner.anonymous(owner_id)
    )


@icontract.require(
    lambda state, new_project_id, name, description, owner:
        state is not None and
        state.validate() and
        new_project_id not in state.projects and
        len(name) > 0 and
        len(name) <= 255 and
        len(description) <= 1000 and
        _project_name_unique(state, name, owner),
    "Preconditions: Valid state, unique project ID, name length 1-255, description <= 1000, name unique for owner"
)
@icontract.snapshot(lambda state, new_project_id, name, description, owner: state.projects.keys(), name="old_project_ids")
@icontract.ensure(
    lambda result, state, new_project_id, name, description, owner, OLD:
        result[0].validate() and
        (result[1].success == True) == (new_project_id in result[0].projects),
    "Postconditions: Valid state, project created iff success"
)
def create_project_core(
    state: SystemState,
    new_project_id: str,
    name: str,
    description: str,
    owner: Owner
) -> tuple[SystemState, Result]:
    """
    Create project: Pure function matching Dafny CreateProject.
    
    Args:
        state: Current system state snapshot
        new_project_id: UUID generated by Shell
        name: Project name (must be unique for owner, case-insensitive)
        description: Project description
        owner: Owner (Authenticated or Anonymous)
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/project_management.dfy :: CreateProject
    """
    # Check name uniqueness
    if not _project_name_unique(state, name, owner):
        return (state, Result.failure("Conflict", "Name taken"))
    
    # Create new project with empty file_ids set
    new_project = Project(
        project_id=new_project_id,
        name=name,
        description=description,
        owner=owner,
        file_ids=set()
    )
    
    # Update projects map
    new_projects = {**state.projects, new_project_id: new_project}
    new_state = SystemState(projects=new_projects, files=state.files)
    new_state.validate()
    
    return (new_state, Result.ok(new_project_id))


@icontract.require(
    lambda state, project_id, owner_id:
        state is not None and
        state.validate() and
        project_id in state.projects and
        _check_project_ownership(state, project_id, owner_id),
    "Preconditions: Valid state, project exists, owner matches"
)
@icontract.snapshot(lambda state, project_id, owner_id: state.files.keys(), name="old_file_ids")
@icontract.ensure(
    lambda result, state, project_id, owner_id, OLD:
        result[0].validate() and
        (result[1].success == True) == (
            project_id not in result[0].projects and
            all(fid not in result[0].files for fid in OLD.old_file_ids 
                if state.files.get(fid) and state.files[fid].project_id == project_id)
        ),
    "Postconditions: Valid state, project and all its files deleted iff success"
)
def delete_project_core(
    state: SystemState,
    project_id: str,
    owner_id: str
) -> tuple[SystemState, Result]:
    """
    Delete project: Pure function matching Dafny DeleteProject.
    
    Cascade deletion: Removes project and all files belonging to it.
    
    Args:
        state: Current system state snapshot
        project_id: Project to delete
        owner_id: Owner identifier
    
    Returns:
        Tuple of (new SystemState, Result)
    
    See: api/verification/project_management.dfy :: DeleteProject
    """
    if project_id not in state.projects:
        return (state, Result.failure("NotFound", "Project not found"))
    
    # Check ownership
    if not _check_project_ownership(state, project_id, owner_id):
        return (state, Result.failure("Unauthorized", "Project ownership mismatch"))
    
    # Cascade: Identify files to remove
    files_to_delete = {
        file_id for file_id, file_obj in state.files.items()
        if file_obj.project_id == project_id
    }
    
    # Remove files
    new_files = {
        file_id: file_obj for file_id, file_obj in state.files.items()
        if file_id not in files_to_delete
    }
    
    # Remove project
    new_projects = {
        pid: proj for pid, proj in state.projects.items()
        if pid != project_id
    }
    
    new_state = SystemState(projects=new_projects, files=new_files)
    new_state.validate()
    
    return (new_state, Result.ok(True))
